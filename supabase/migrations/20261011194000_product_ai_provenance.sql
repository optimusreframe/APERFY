-- Keep AI provenance in a separate admin-only table. Keeping it out of
-- products is deliberate: products has authenticated storefront reads, while
-- these markers must never be visible to customers.
create table if not exists public.product_ai_provenance (
  product_id uuid primary key references public.products(id) on delete cascade,
  ai_image_generation_id text,
  ai_image_generated_at timestamptz,
  ai_price_generation_id text,
  ai_price_generated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.product_ai_provenance enable row level security;

drop policy if exists "Admins manage product AI provenance" on public.product_ai_provenance;
create policy "Admins manage product AI provenance"
  on public.product_ai_provenance
  for all
  to authenticated
  using (public.has_role(auth.uid(), 'admin'))
  with check (public.has_role(auth.uid(), 'admin'));

revoke all on table public.product_ai_provenance from anon;
grant select, insert, update, delete on table public.product_ai_provenance to authenticated;

create index if not exists product_ai_provenance_image_idx
  on public.product_ai_provenance (ai_image_generation_id)
  where ai_image_generation_id is not null;

create index if not exists product_ai_provenance_price_idx
  on public.product_ai_provenance (ai_price_generation_id)
  where ai_price_generation_id is not null;

-- Backfill products whose stored media points to an image generated by the
-- protected AI image pipeline. generated-angles are also AI media, even when
-- they were added as a secondary gallery image instead of the cover image.
insert into public.product_ai_provenance (
  product_id,
  ai_image_generation_id,
  ai_image_generated_at
)
select p.id,
       'legacy-ai-image-' || md5(media.value),
       coalesce(p.updated_at, now())
from public.products as p
cross join lateral (
  select media.value
  from jsonb_array_elements_text(
    case when jsonb_typeof(p.images) = 'array' then p.images else '[]'::jsonb end
  ) as media(value)
  where media.value like '%/generated-angles/%'
     or (media.value like '%/composed-results/%' and media.value not like '%-non_ai-%')
  limit 1
) as media
where not exists (
  select 1
  from public.product_ai_provenance as existing
  where existing.product_id = p.id
)
on conflict (product_id) do update
set ai_image_generation_id = coalesce(public.product_ai_provenance.ai_image_generation_id, excluded.ai_image_generation_id),
    ai_image_generated_at = coalesce(public.product_ai_provenance.ai_image_generated_at, excluded.ai_image_generated_at),
    updated_at = now();
